"""Lambda adapter behind an AgentCore Gateway Lambda target.

Responsibilities that Gateway does NOT provide (and this code must):
  * partition (entity / plant) scope on every backend query,
  * idempotent writes keyed by idempotency_key + caller,
  * T3 actions create a PENDING approval bound to the exact intent; they never execute directly,
  * bounded, paginated responses.

Replace the `backend_*` stubs with calls to the system of record.
Event/context contract: https://docs.aws.amazon.com/bedrock-agentcore/latest/devguide/gateway-add-target-lambda.html
"""

import hashlib
import json
import os
import time
import uuid

import boto3
from botocore.exceptions import ClientError

from tool_registry import TOOL_KINDS  # generated by scaffold_deploy.py from mcp-spec.yaml

TABLE = boto3.resource("dynamodb").Table(os.environ["STATE_TABLE"])
DELIM = "___"


class Rejected(Exception):
    """Business rejection returned to the agent as a tool error."""


# --- context -------------------------------------------------------------------

def _tool_name(context):
    full = context.client_context.custom["bedrockAgentCoreToolName"]
    return full[full.index(DELIM) + len(DELIM):] if DELIM in full else full


def _trusted(event):
    ctx = event.pop("_trusted_context", None)
    if not ctx or not ctx.get("sub"):
        raise Rejected("missing trusted context (interceptor not applied)")
    return ctx


# --- idempotency ------------------------------------------------------------------

def _idempotent(ctx, tool, event, fn):
    key = event.get("idempotency_key")
    if not key:
        raise Rejected("idempotency_key is required for this tool")
    intent = hashlib.sha256(json.dumps({k: v for k, v in event.items() if k != "idempotency_key"},
                                       sort_keys=True).encode()).hexdigest()
    pk = f"IDEM#{ctx['sub']}#{tool}#{key}"
    try:
        TABLE.put_item(
            Item={"pk": pk, "sk": "claim", "intent": intent, "status": "IN_PROGRESS",
                  "expiresAt": int(time.time()) + 7 * 86400},
            ConditionExpression="attribute_not_exists(pk)",
        )
    except ClientError as err:
        if err.response["Error"]["Code"] != "ConditionalCheckFailedException":
            raise
        prior = TABLE.get_item(Key={"pk": pk, "sk": "claim"})["Item"]
        if prior["intent"] != intent:
            raise Rejected("idempotency_key reused with different arguments") from None
        if prior["status"] != "DONE":
            raise Rejected("previous attempt outcome unknown — reconciliation pending, do not retry") from None
        return json.loads(prior["result"])
    result = fn()
    TABLE.update_item(Key={"pk": pk, "sk": "claim"},
                      UpdateExpression="SET #s = :d, #r = :r",
                      ExpressionAttributeNames={"#s": "status", "#r": "result"},
                      ExpressionAttributeValues={":d": "DONE", ":r": json.dumps(result)})
    return result


# --- backend stubs (replace) ------------------------------------------------------

def backend_read(ctx, tool, event):
    # MUST filter by ctx["partition"] in the query itself, never by an argument.
    return {"items": [], "partition": ctx["partition"], "next_page_token": None}


def backend_write(ctx, tool, event):
    return {"draft_id": str(uuid.uuid4()), "status": "DRAFT"}


def request_approval(ctx, tool, event):
    approval_id = str(uuid.uuid4())
    TABLE.put_item(Item={
        "pk": f"APPROVAL#{approval_id}", "sk": "request", "status": "PENDING",
        "requestedBy": ctx["sub"], "partition": ctx["partition"], "tool": tool,
        "intent": json.dumps(event, sort_keys=True), "expiresAt": int(time.time()) + 86400,
    })
    # Notify approvers (EventBridge / Step Functions) here. Execution happens only
    # after an approver with domain entitlement signs this exact intent.
    return {"approval_id": approval_id, "status": "PENDING_APPROVAL"}


HANDLERS = {"read": backend_read, "write": backend_write, "approval": request_approval}


def lambda_handler(event, context):
    try:
        tool = _tool_name(context)
        ctx = _trusted(event)
        kind = TOOL_KINDS.get(tool)
        if kind is None:
            raise Rejected(f"unknown tool {tool}")
        handler = HANDLERS[kind]
        if kind == "read":
            return handler(ctx, tool, event)
        return _idempotent(ctx, tool, event, lambda: handler(ctx, tool, event))
    except Rejected as rej:
        return {"error": str(rej)}
