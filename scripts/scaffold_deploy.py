#!/usr/bin/env python3
"""Scaffold a deployable CDK project for one MCP server from its mcp-spec.

    scaffold_deploy.py mcp-spec.yaml -o infra/ [--force]

Writes:
  infra/                       copy of templates/cdk (stack, Lambdas, CI workflow)
  infra/config/tools.json      AgentCore Lambda-target tool schemas (inline payload)
  infra/config/mcp.json        names, scopes, partition claim, Region
  infra/policies/*.cedar       default-deny permits, one per tool (deployed)
  infra/policies/breakglass/   pre-authored forbid per tool (NOT deployed)
  infra/tests/decision-matrix.md   positive/negative cases every policy change must pass

Cedar placeholders ${GatewayArn} are substituted by the stack at deploy time.
Verify every generated identifier against the Cedar schema AgentCore generates
from your deployed tools before switching a policy to ACTIVE.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys

from spec_io import load_spec

HERE = os.path.dirname(os.path.abspath(__file__))
TEMPLATE = os.path.join(HERE, "..", "skills", "mcp-iac-deploy", "templates", "cdk")
TIER_SCOPE = {"T0": "read", "T1": "read", "T2": "write", "T3": "propose"}
TYPE_MAP = {"string": "string", "integer": "integer", "number": "number", "boolean": "boolean",
            "enum": "string", "date": "string"}


def target_name(spec: dict) -> str:
    """Gateway target name; Cedar actions are <TargetName>___<tool>."""
    name = re.sub(r"[^A-Za-z0-9]", "", (spec["mcp"]["name"].title()))
    return f"{name}Tools"


def tool_schema(tool: dict) -> dict:
    props, required = {}, []
    for inp in tool.get("inputs") or []:
        desc = inp.get("constraints", "")
        if inp.get("type") == "enum":
            desc = f"One of: {desc}"
        if inp.get("type") == "date":
            desc = f"ISO-8601 date. {desc}".strip()
        props[inp["name"]] = {"type": TYPE_MAP.get(inp.get("type", "string"), "string"),
                              "description": desc or inp["name"]}
        if inp.get("required", True):
            required.append(inp["name"])
    return {
        "name": tool["name"],
        "description": " ".join(tool.get("description", "").split()),
        "inputSchema": {"type": "object", "properties": props, "required": required},
    }


def scope_claim(spec: dict) -> str:
    """Entra ID puts delegated scopes in `scp`; most other IdPs use `scope`."""
    idp = (spec.get("context") or {}).get("identity_provider", "")
    return "scp" if idp in ("entra-id", "azure-ad") else "scope"


def tool_kind(tool: dict) -> str:
    if tool.get("tier") == "T3" or tool.get("approval") == "required":
        return "approval"
    return "read" if tool.get("side_effect", "none") == "none" else "write"


def cedar_permit(spec: dict, tool: dict, tname: str) -> str:
    domain = spec["mcp"]["domain"]
    sc = scope_claim(spec)
    claim = (spec.get("context") or {}).get("partition_dimension", "none")
    scope = f"{domain}/{TIER_SCOPE[tool['tier']]}"
    lines = [
        f"// {tool['name']} - tier {tool['tier']}, side effect {tool.get('side_effect', 'none')}",
        f"// Generated by mcp-architect. Owner: {spec['mcp'].get('technical_owner', '?')}",
        "permit(",
        "  principal is AgentCore::OAuthUser,",
        f'  action == AgentCore::Action::"{tname}___{tool["name"]}",',
        '  resource == AgentCore::Gateway::"${GatewayArn}"',
        ")",
        "when {",
        f'  principal.hasTag("{sc}") &&',
        f'  principal.getTag("{sc}") like "*{scope}*"',
    ]
    if tool.get("partition_scoped") and claim not in ("none", "", None):
        lines.append(f'  && principal.hasTag("{claim}")')
    for inp in tool.get("inputs") or []:
        c = str(inp.get("constraints", ""))
        m = re.match(r"^\s*(\d+)\s*\.\.\s*(\d+)\s*$", c)
        if m and inp.get("type") in ("integer", "number"):
            lines.append(f"  && context.input.{inp['name']} >= {m.group(1)} && context.input.{inp['name']} <= {m.group(2)}")
    if tool["tier"] in ("T2", "T3"):
        lines.append("  // TODO(domain owner): add business-limit conditions on context.input.* (amount, plant, quantity)")
    lines.append("};")
    return "\n".join(lines) + "\n"


def cedar_forbid(tname: str, tool: dict) -> str:
    return (
        f"// BREAK-GLASS - emergency shutdown of {tool['name']}. Promote via the fast-track pipeline only.\n"
        "forbid(\n"
        "  principal,\n"
        f'  action == AgentCore::Action::"{tname}___{tool["name"]}",\n'
        '  resource == AgentCore::Gateway::"${GatewayArn}"\n'
        ");\n"
    )


def decision_matrix(spec: dict, tname: str) -> str:
    domain = spec["mcp"]["domain"]
    claim = (spec.get("context") or {}).get("partition_dimension", "none")
    rows = ["| # | Tool | Caller | Arguments | Expected tools/list | Expected tools/call | Backend expectation |",
            "| --- | --- | --- | --- | --- | --- | --- |"]
    n = 1
    for t in spec.get("tools") or []:
        scope = f"{domain}/{TIER_SCOPE[t['tier']]}"
        a = f"`{tname}___{t['name']}`"
        rows.append(f"| {n} | {a} | scope `{scope}` + {claim} claim | valid | visible | allowed | returns own-{claim} data only |"); n += 1
        rows.append(f"| {n} | {a} | no `{scope}` scope | valid | hidden | denied (default deny) | not invoked |"); n += 1
        if t.get("partition_scoped"):
            rows.append(f"| {n} | {a} | scope ok, **missing** {claim} claim | valid | hidden | denied | not invoked |"); n += 1
            rows.append(f"| {n} | {a} | scope ok, {claim}=A | record of {claim} B | visible | allowed by Cedar | **rejects** (backend scope) |"); n += 1
            rows.append(f"| {n} | {a} | scope ok | forged `{claim}` / `_trusted_context` in arguments | visible | allowed | interceptor overwrites; backend ignores forged value |"); n += 1
        if t.get("side_effect") != "none":
            rows.append(f"| {n} | {a} | scope ok | same idempotency_key twice | visible | allowed | second call returns first result, no duplicate write |"); n += 1
        if t["tier"] == "T3":
            rows.append(f"| {n} | {a} | scope ok | valid, no approval yet | visible | allowed | creates PENDING approval only; nothing executed |"); n += 1
        rows.append(f"| {n} | {a} | any | break-glass forbid deployed | hidden | denied (forbid wins) | not invoked |"); n += 1
    return (
        f"# Policy decision matrix — {spec['mcp']['name']}\n\n"
        "Run against stage in LOG_ONLY, then ENFORCE, on every policy, schema or tool change. "
        "A Cedar allow is never evidence of business correctness: the backend column must also pass.\n\n"
        + "\n".join(rows) + "\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("spec")
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--force", action="store_true", help="overwrite an existing output directory")
    a = ap.parse_args()
    spec = load_spec(a.spec)
    out = a.output
    if os.path.exists(out) and os.listdir(out) and not a.force:
        sys.exit(f"{out} exists and is not empty (use --force)")
    shutil.copytree(TEMPLATE, out, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns("node_modules", "cdk.out", "*.js", "*.d.ts"))
    tname = target_name(spec)
    lambda_tools = [t for t in spec.get("tools") or [] if t.get("target_type", "lambda") == "lambda"]
    skipped = [t["name"] for t in spec.get("tools") or [] if t not in lambda_tools]

    os.makedirs(os.path.join(out, "config"), exist_ok=True)
    with open(os.path.join(out, "config", "tools.json"), "w") as fh:
        json.dump([tool_schema(t) for t in lambda_tools], fh, indent=2)
    ctx = spec.get("context") or {}
    with open(os.path.join(out, "config", "mcp.json"), "w") as fh:
        json.dump({
            "name": spec["mcp"]["name"],
            "domain": spec["mcp"]["domain"],
            "targetName": tname,
            "region": ctx.get("primary_region", "eu-central-1"),
            "partitionClaim": ctx.get("partition_dimension", "none"),
            "discoveryUrl": "https://login.microsoftonline.com/<tenant-id>/v2.0/.well-known/openid-configuration",
            "allowedAudience": [f"api://mcp-{spec['mcp']['name']}"],
            "tags": {"mcp:name": spec["mcp"]["name"], "mcp:domain": spec["mcp"]["domain"],
                     "cost-center": "unassigned"},
        }, fh, indent=2)

    with open(os.path.join(out, "lambda", "adapter", "tool_registry.py"), "w") as fh:
        fh.write('"""Generated by scaffold_deploy.py: tool name -> read | write | approval."""\n\n')
        fh.write("TOOL_KINDS = " + json.dumps({t["name"]: tool_kind(t) for t in lambda_tools}, indent=4) + "\n")

    pol = os.path.join(out, "policies")
    os.makedirs(os.path.join(pol, "breakglass"), exist_ok=True)
    for t in lambda_tools:
        with open(os.path.join(pol, f"{t['name']}.cedar"), "w") as fh:
            fh.write(cedar_permit(spec, t, tname))
        with open(os.path.join(pol, "breakglass", f"forbid_{t['name']}.cedar"), "w") as fh:
            fh.write(cedar_forbid(tname, t))
    os.makedirs(os.path.join(out, "tests"), exist_ok=True)
    with open(os.path.join(out, "tests", "decision-matrix.md"), "w") as fh:
        fh.write(decision_matrix(spec, tname))

    print(f"scaffolded {out}: {len(lambda_tools)} Lambda tools, target {tname}")
    if skipped:
        print(f"not scaffolded (non-Lambda targets, add manually): {', '.join(skipped)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
