#!/usr/bin/env python3
"""Generate an editable draw.io AWS architecture diagram from an mcp-spec.

    gen_architecture.py mcp-spec.yaml -o docs/architecture.drawio

The layout follows the per-domain gateway reference pattern: clients and IdP on
the left, a platform account (Gateway, Policy, Identity, interceptor, approvals),
a domain workload account holding one lane per target type, a log-archive
account, and systems of record grouped by location. Export with
export_drawio.sh to get an SVG.
"""

from __future__ import annotations

import argparse
import sys

from drawio_kit import AMBER_DARK, GREEN, LINE, MIST, NAVY, TEAL, Diagram, write_file
from spec_io import load_spec

TARGET_ICON = {
    "lambda": ("lambda", "Lambda adapter"),
    "openapi": ("ecs", "OpenAPI service"),
    "mcp_server": ("ecs", "MCP server"),
    "runtime": ("fargate", "AgentCore Runtime"),
    "http_passthrough": ("ecs", "HTTP endpoint"),
    "smithy": ("lambda", "Smithy API"),
    "api_gateway": ("api_gateway", "API Gateway (regional)"),
}
PRIVATE_VIA_LATTICE = {"openapi", "mcp_server", "http_passthrough"}


def build(spec: dict) -> Diagram:
    mcp = spec.get("mcp") or {}
    ctx = spec.get("context") or {}
    tools = spec.get("tools") or []
    sors = spec.get("systems_of_record") or []
    tiers = {t.get("tier") for t in tools}
    targets: dict[str, list[dict]] = {}
    for t in tools:
        targets.setdefault(t.get("target_type", "lambda"), []).append(t)

    lane_w = 250
    n_lanes = max(len(targets), 1)
    dom_w = max(560, 60 + n_lanes * lane_w)
    width = 380 + max(dom_w, 760) + 380
    height = 1000
    d = Diagram(
        f"{mcp.get('name', 'mcp')}-architecture",
        f"{mcp.get('name', 'MCP server')} — AWS architecture ({ctx.get('primary_region', 'region tbd')})",
        width=width, height=height,
        subtitle=f"Domain: {mcp.get('domain', '?')} · owner: {mcp.get('technical_owner', '?')} · "
                 f"partition: {ctx.get('partition_dimension', 'none')} · generated by mcp-architect from mcp-spec.yaml",
        footer="Generated conceptual architecture. Verify Region features, trusted-context transport and private connectivity per target before production.",
    )

    # Left: consumers, IdP
    d.group("ext", 30, 120, 300, 470, "Consumers", kind="plain")
    d.aws("users", 150, 160, "users", "Users")
    names = ", ".join(c.get("name", "?") for c in spec.get("consumers") or []) or "agents"
    d.aws("clients", 150, 280, "client", "Agents / MCP clients")
    d.text("client_names", 45, 530, 270, 50, "Consumers: " + names, size=11, align="center")
    d.box("idp", 55, 450, 250, 70, f"IdP: {ctx.get('identity_provider', 'tbd')}\nJWT with {ctx.get('partition_dimension', 'no')} claim",
          fill="#EEF2FA", stroke="#3B5BA9", size=12)
    d.edge("users", "clients")
    d.edge("clients", "idp", "1 sign-in", dashed=True)

    # AWS cloud
    ax = 360
    aw = max(dom_w, 760) + 20
    d.group("aws", ax, 120, aw + 360, 800, f"AWS Cloud · {ctx.get('primary_region', '')}", kind="region")

    # Platform account
    px, py = ax + 20, 160
    d.group("plat", px, py, aw - 20, 330, "MCP platform account", kind="account")
    d.aws("pl", px + 30, py + 70, "vpc_privatelink", "Private ingress")
    d.aws("gw", px + 170, py + 70, "bedrock", f"AgentCore Gateway\n({mcp.get('domain', 'domain')})", size=64)
    d.aws("policy", px + 330, py + 70, "verified_permissions", "Policy (Cedar)\nENFORCE")
    d.aws("ident", px + 470, py + 70, "identity_and_access_management", "AgentCore Identity")
    d.aws("kms", px + 610, py + 70, "key_management_service", "KMS")
    d.edge("clients", "pl", "2 MCP + JWT", color=AMBER_DARK, width=2.2)
    d.edge("pl", "gw", "", color=AMBER_DARK, width=2.2)
    d.edge("gw", "policy", "3 authorize")
    row2 = py + 200
    if any(t.get("partition_scoped") for t in tools):
        d.aws("icpt", px + 170, row2, "lambda", "Interceptor\n(trusted context)")
        d.edge("gw", "icpt", "4", exit=(1, 0.9), entry=(0.5, 0),
               waypoints=[(px + 252, py + 128), (px + 252, row2 - 20), (px + 198, row2 - 20)])
    d.aws("registry", px + 330, row2, "dynamodb", "Tool registry")
    if "T3" in tiers:
        d.aws("approve", px + 470, row2, "step_functions", "Approval workflow")
    if ctx.get("user_delegation_to_saas"):
        d.box("saas", px + 590, row2, 140, 56, "SaaS (3LO)", fill="#FFFFFF", stroke="#7D8998", size=12)
        d.edge("ident", "saas", "per-user OAuth", dashed=True)

    # Domain workload account
    dy = py + 360
    d.group("dom", px, dy, aw - 20, 380, f"Domain workload account — {mcp.get('domain', '')}", kind="account")
    d.group("vpc", px + 20, dy + 40, aw - 60, 320, "VPC (private subnets)", kind="vpc")
    needs_lattice = any(k in PRIVATE_VIA_LATTICE for k in targets)
    lane_x = px + 50
    if needs_lattice:
        d.aws("lattice", lane_x, dy + 100, "vpc_lattice", "VPC Lattice")
        lane_x += 150
    prev = None
    for i, (ttype, ttools) in enumerate(targets.items()):
        icon, label = TARGET_ICON.get(ttype, ("lambda", ttype))
        cid = f"tgt_{ttype}"
        d.aws(cid, lane_x + i * lane_w, dy + 100, icon, label)
        listing = "<br>".join(f"{t.get('name')} <b>[{t.get('tier')}]</b>" for t in ttools)
        d.box(f"{cid}_tools", lane_x + i * lane_w - 80, dy + 200, 240, 30 + 18 * len(ttools), listing,
              fill=MIST, stroke=LINE, size=11)
        if ttype in PRIVATE_VIA_LATTICE and needs_lattice:
            d.edge("lattice", cid, "", color=AMBER_DARK, width=2)
        else:
            d.edge("gw", cid, "5", color=AMBER_DARK, width=2, exit=(0, 0.9), entry=(0.5, 0),
                   waypoints=[(px + 150, py + 128), (px + 150, dy + 70), (lane_x + i * lane_w + 28, dy + 70)])
        prev = cid
    if needs_lattice:
        d.edge("gw", "lattice", "5 private egress", color=AMBER_DARK, width=2, exit=(0, 0.9), entry=(0.5, 0),
               waypoints=[(px + 150, py + 128), (px + 150, dy + 70), (px + 78, dy + 70)])
    if any(t.get("idempotency") == "key" for t in tools) and prev:
        d.aws("idem", px + aw - 120, dy + 100, "dynamodb", "Idempotency store")
    if "T3" in tiers and prev:
        last_x = lane_x + (len(targets) - 1) * lane_w
        d.edge("approve", prev, "approved intent", dashed=True, color=GREEN, exit=(1, 0.5), entry=(0.8, 0),
               waypoints=[(px + 545, row2 + 28), (px + 545, dy + 85), (last_x + 45, dy + 85)])

    # Log archive
    lx = ax + aw + 20
    d.group("logs", lx, 160, 320, 330, "Log-archive / security account", kind="account")
    d.aws("trail", lx + 40, 230, "cloudtrail", "CloudTrail")
    d.aws("cw", lx + 190, 230, "cloudwatch", "CloudWatch")
    d.aws("evid", lx + 40, 370, "s3", "Evidence (Object Lock)")
    d.aws("hub", lx + 190, 370, "security_hub", "Security Hub")
    d.edge("gw", "cw", "telemetry", dashed=True, color=TEAL, exit=(0.5, 0), entry=(0.5, 0),
           waypoints=[(px + 202, py + 50), (lx + 218, py + 50)])
    d.edge("cw", "evid", "", dashed=True, color=TEAL)

    # Systems of record
    d.group("sor", lx, dy, 320, 380, "Systems of record", kind="datacenter")
    for j, s in enumerate(sors[:5]):
        sid = f"sor{j}"
        d.box(sid, lx + 20, dy + 50 + j * 64, 280, 52,
              f"<b>{s.get('name')}</b><br>{s.get('location')} · {s.get('interface')}", fill="#FFFFFF", stroke=NAVY, size=11)
    if sors and targets:
        conn = "Direct Connect / TGW" if any(s.get("location") == "on-prem" for s in sors) else "private"
        first_target = f"tgt_{next(iter(targets))}"
        d.edge(first_target, "sor0", f"6 {conn}", color=AMBER_DARK, width=2, exit=(1, 0.5), entry=(0, 0.5))

    d.legend(40, 640, [("Tool call path", AMBER_DARK, False), ("Control / identity", NAVY, False),
                       ("Telemetry", TEAL, True), ("Approval", GREEN, True)])
    return d


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("spec")
    ap.add_argument("-o", "--output", default="architecture.drawio")
    a = ap.parse_args()
    write_file(a.output, [build(load_spec(a.spec))])
    print(a.output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
